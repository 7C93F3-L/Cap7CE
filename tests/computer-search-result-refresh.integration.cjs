const assert = require("node:assert/strict");
const path = require("node:path");
const Module = require("node:module");
const esbuild = require("esbuild");
const file = path.resolve(__dirname, "../src/renderer/computer-search/computerSearchResultRefresh.ts");
const compiled = esbuild.buildSync({entryPoints:[file],bundle:true,write:false,platform:"node",format:"cjs",logLevel:"silent"});
const loaded = new Module(file, module); loaded.filename=file; loaded.paths=module.paths;
loaded._compile(compiled.outputFiles[0].text, file);
const {readComputerSearchReplacement: read, MetadataResultRefreshGate: Gate} = loaded.exports;
const progress = (processed, phase="extracting") => ({processed, failed:0, unsupported:0, phase});

(async () => {
  const gate = new Gate();
  gate.observe(progress(0)); assert.equal(gate.next(0),null);
  gate.observe(progress(10)); assert.deepEqual(gate.next(0),{stamp:"1",delay:0});
  gate.finish("1",100,"applied"); assert.equal(gate.next(100),null);
  gate.observe(progress(20)); assert.equal(gate.next(100).delay,5000);
  gate.observe(progress(21)); assert.equal(gate.next(100).delay,5000);
  gate.finish("2",200,"applied"); assert.equal(gate.next(200).stamp,"3","an older completion cannot consume a newer observation");
  gate.observe(progress(21,"completed")); assert.equal(gate.next(201).delay,0);
  gate.finish("4",201,"deferred"); assert.equal(gate.next(202).delay,0);
  gate.finish("4",202,"applied");
  for(let i=0;i<10;i++) gate.observe(progress(21,"completed"));
  assert.equal(gate.next(100000),null,"completed unchanged observations cannot create idle polling");
  gate.observe(progress(0,"preparing")); gate.observe(progress(1,"extracting"));
  const failureStamp = gate.next(100000).stamp;
  for(let i=0;i<3;i++) gate.finish(failureStamp,100000+i*5000,"failed");
  assert.equal(gate.next(200000),null,"a terminal or transient failure cannot retry forever");
  gate.observe(progress(2)); assert.ok(gate.next(200000),"new progress can recover after bounded failures");
  const previousRunStamp = gate.next(200000).stamp;
  gate.observe(progress(0,"preparing")); gate.observe(progress(2));
  gate.finish(previousRunStamp,200000,"applied");
  assert.ok(gate.next(200000),"the same counts in a new run are a different pending observation");
  const initialComplete = new Gate(); initialComplete.observe(progress(100,"completed"));
  assert.equal(initialComplete.next(0),null,"mounting an already completed build needs no duplicate query");
  const catalogGate = new Gate(); catalogGate.observeCatalog(1);
  assert.equal(catalogGate.next(0),null,"initial catalog snapshot needs no duplicate query");
  catalogGate.observeCatalog(2); const catalogStamp = catalogGate.next(0).stamp;
  catalogGate.finish(catalogStamp,0,"deferred"); assert.equal(catalogGate.next(1).stamp,catalogStamp);
  catalogGate.finish(catalogStamp,1,"applied");
  for(let i=0;i<100;i++) catalogGate.observeCatalog(2);
  assert.equal(catalogGate.next(100000),null,"unchanged catalog notices cannot produce idle queries");
  catalogGate.observeCatalog(0); assert.ok(catalogGate.next(100000),"a fresh Catalog reset can refresh filename-only views");

  const request = {taskId:"replacement",query:"submitted-query",scopePath:null};
  const calls = [];
  const page = (items,cursor) => ({taskId:"replacement",items:items.map(id=>({id})),nextCursor:cursor,isComplete:!cursor,catalogRevision:7});
  const api = { async search(input) {calls.push(input);return page(["a","b"],"new-page-2");},
    async nextPage(input) {calls.push(input);return page(["c","d"],"new-page-3");} };
  const refreshed = await read(api,request,3,()=>true);
  assert.deepEqual(refreshed.items.map(item=>item.id),["a","b","c","d"]);
  assert.equal(refreshed.nextCursor,"new-page-3");
  assert.deepEqual(calls,[request,{taskId:"replacement",cursor:"new-page-2"}],"only new signed cursors are reused and the loaded extent is retained");
  const reduced = await read({search:async()=>page(["a"],null),nextPage:()=>{throw Error("unexpected")}},request,100,()=>true);
  assert.equal(reduced.items.length,1,"a reduced result set must not retain old unmatched rows");
  let current=true; let pages=0;
  const superseded = await read({search:async()=>page(["a"],"next"),nextPage:async()=>{pages++;current=false;return page(["b"],"later");}},request,10,()=>current);
  assert.equal(superseded,null);assert.equal(pages,1,"superseded work stops before any further page fetch");
  await assert.rejects(read({search:async()=>page(["a"],"repeat"),nextPage:async()=>page(["b"],"repeat")},request,10,()=>true),/repeated-cursor/);
  await assert.rejects(read({search:async()=>page(["a"],"next"),nextPage:async()=>page([],"later")},request,10,()=>true),/empty-page/);
  await assert.rejects(read({search:async()=>{throw Error("transient-deadline")}},request,10,()=>true),/transient-deadline/);
  console.log(JSON.stringify({metadataResultRefresh:"ok",throttled:true,finalFlush:true,noIdlePolling:true,boundedRetries:true,signedPagesRebuilt:true,supersededDiscarded:true}));
})().catch(error=>{console.error(error);process.exitCode=1;});
