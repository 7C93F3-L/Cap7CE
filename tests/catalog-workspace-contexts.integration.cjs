const assert = require("node:assert/strict");
const compiled = require("esbuild").buildSync({ entryPoints: [require("node:path").join(__dirname, "../src/renderer/catalog-workspace/catalogWorkspaceContexts.ts")], bundle: true, platform: "node", write: false }).outputFiles[0].text;
const model = { exports: {} }; new Function("module", "exports", "require", compiled)(model, model.exports, require);
const { createCatalogWorkspace, catalogWorkspaceReducer: reduce, maximumCatalogContexts } = model.exports;
let state = createCatalogWorkspace("All files");
const freshHome = reduce(state, { type: "close", id: state.activeId });
assert.notEqual(freshHome.activeId, state.activeId, "Closing the last page creates a fresh query owner");
assert.equal(freshHome.contexts.length, 1);
assert.equal(freshHome.contexts[0].name, "All files");
assert.equal(freshHome.contexts[0].scopePath, null);
let tabs = reduce(state, { type: "new-tab", scopePath: null, name: "New tab" });
tabs = reduce(tabs, { type: "new-tab", scopePath: null, name: "New tab" });
assert.equal(tabs.contexts.length, 3, "Explicit new-page actions do not deduplicate");
const tabOwner = tabs.activeId;
tabs = reduce(tabs, { type: "location", id: tabOwner, path: "Y:\\Folder" });
assert.equal(tabs.contexts.at(-1).displayName, "Folder");
assert.equal(tabs.contexts[0].displayName, undefined);
assert.equal(reduce(tabs, { type: "location", id: tabOwner, path: "Y:\\Folder" }), tabs);
tabs = reduce(tabs, { type: "close", id: "catalog:all" });
assert.equal(tabs.activeId, tabOwner, "The initial home is closable without switching an inactive page");
tabs = reduce(tabs, { type: "location", id: tabOwner, path: null });
assert.equal(tabs.contexts.at(-1).displayName, undefined);
const replaced = reduce(tabs, { type: "replace", scopePath: "Y:\\Favorite", name: "Favorite" });
assert.equal(replaced.contexts.find(context => context.id === replaced.activeId).kind, "browse", "Opening the browser uses hierarchical navigation");
assert.equal(replaced.contexts.length, tabs.contexts.length, "A directory click replaces the current page without adding tabs");
assert.notEqual(replaced.activeId, tabs.activeId, "Changing the directory retires its former query owner");
assert.equal(replaced.contexts[0], tabs.contexts[0], "Other open pages retain their query identity");
state = reduce(state, { type: "open", scopePath: "Y:\\Fixtures", name: "Fixtures" });
const first = state.contexts[1], firstId = state.activeId;
state = reduce(state, { type: "open", scopePath: "y:/fixtures/", name: "Another alias" });
assert.equal(state.contexts.length, 2);
assert.equal(state.activeId, firstId);
assert.equal(state.contexts[1], first, "Selecting a scope must retain its mounted identity and query owner");
state = reduce(state, { type: "open", scopePath: "Y:\\Fixtures\\Nested", name: "Nested" });
const secondId = state.activeId;
state = reduce(state, { type: "favorite-names", directories: [{ id: "fav", path: "y:\\fixtures\\", name: "Renamed" }] });
assert.equal(state.contexts[1].id, firstId);
assert.equal(state.contexts[1].name, "Renamed");
const renamed = state;
assert.equal(reduce(state, { type: "favorite-names", directories: [] }), renamed,
  "Removing all favorites cannot close, switch or rename open views");
state = reduce(state, { type: "close", id: firstId });
assert.equal(state.activeId, secondId, "Closing an inactive view cannot switch the current view");
state = reduce(state, { type: "close", id: secondId });
assert.equal(state.activeId, "catalog:all");
state = reduce(state, { type: "open", scopePath: "Y:\\Fixtures", name: "Again" });
assert.notEqual(state.activeId, firstId, "Reopening must create a fresh owner after previous query retirement");
const searchOwner = state.contexts.find(context => context.id === state.activeId);
state = reduce(state, { type: "open", kind: "browse", scopePath: "y:/fixtures/", name: "Browser" });
const browserOwner = state.contexts.find(context => context.id === state.activeId);
assert.notEqual(browserOwner.id, searchOwner.id, "Browsing cannot replace the search query owner at the same path");
assert.equal(state.contexts.find(context => context.id === searchOwner.id), searchOwner);
state = reduce(state, { type: "open", kind: "browse", scopePath: "Y:\\Fixtures", name: "Browser again" });
assert.equal(state.activeId, browserOwner.id);
assert.equal(state.contexts.find(context => context.id === browserOwner.id), browserOwner);
state = reduce(state, { type: "open", scopePath: "Y:\\Fixtures", name: "Search again" });
assert.equal(state.activeId, searchOwner.id);
state = reduce(state, { type: "open", kind: "browse", scopePath: null, name: "Skim" });
const browserRoot = state.activeId;
assert.notEqual(browserRoot, "catalog:all");
state = reduce(state, { type: "close", id: browserRoot });
assert.equal(state.contexts.some(context => context.id === browserRoot), false, "Every page is closable");
assert.equal(state.contexts.find(context => context.id === searchOwner.id), searchOwner);
for (let index = state.contexts.length; index < maximumCatalogContexts; index++)
  state = reduce(state, { type: "open", scopePath: `Y:\\Folder${index}`, name: `Folder${index}` });
const full = state;
state = reduce(state, { type: "open", scopePath: "Y:\\Overflow", name: "Overflow" });
assert.equal(state.contexts, full.contexts);
assert.equal(state.activeId, full.activeId);
assert.equal(state.openLimitReached, true, "Capacity cannot silently evict another view");
state = reduce(state, { type: "open", scopePath: null, name: "All files" });
assert.equal(state.activeId, "catalog:all");
assert.equal(state.openLimitReached, false);
const unchanged = state;
assert.equal(reduce(state, { type: "select", id: "unknown" }), unchanged);
assert.equal(reduce(state, { type: "close", id: "unknown" }), unchanged);
assert.equal(reduce(state, { type: "favorite-names", directories: [] }), unchanged);
let entries = createCatalogWorkspace("Computer");
const computer = entries.contexts[0];
entries = reduce(entries, { type: "location", id: computer.id, path: "X:\\Folder" });
entries = reduce(entries, { type: "entry", scopePath: "Y:\\Favorite", name: "Favorite" });
const favorite = entries.contexts[1];
assert.equal(favorite.kind, "browse", "Favorite entry starts in direct-child navigation rather than recursive search");
entries = reduce(entries, { type: "entry", scopePath: null, name: "Computer" });
assert.equal(entries.activeId, computer.id);
assert.equal(entries.contexts[0].displayName, "Folder", "Returning to Computer retains its mounted navigation owner");
entries = reduce(entries, { type: "entry", scopePath: "y:/favorite/", name: "Favorite" });
assert.notEqual(entries.activeId, favorite.id, "Favorite shortcuts retire the old navigation/query owner instead of resuming it");
assert.equal(entries.contexts[1].scopePath, "y:/favorite/");
assert.equal(entries.contexts[1].favoritePath, "y:/favorite/");
assert.equal(entries.contexts[1].displayName, undefined);
const reopenedFavorite = entries.activeId;
entries = reduce(entries, { type: "location", id: reopenedFavorite, path: "Y:\\Favorite\\Nested" });
entries = reduce(entries, { type: "entry", scopePath: "Y:\\Favorite", name: "Favorite" });
assert.notEqual(entries.activeId, reopenedFavorite, "Clicking the active favorite also restores its fixed root");
assert.equal(entries.contexts[1].scopePath, "Y:\\Favorite");
assert.equal(entries.contexts.length, 2);
for (let index = 0; index < 256; index++) entries = reduce(entries, { type: "entry", scopePath: `Y:\\Favorite${index}`, name: `Favorite${index}` });
assert.equal(entries.contexts.length, 2, "Ordinary sidebar navigation does not accumulate mounted result lists");
assert.equal(entries.contexts[0].id, computer.id, "Changing favorites never retires Computer");
entries = reduce(entries, { type: "entry", scopePath: null, name: "Computer" });
assert.equal(entries.activeId, computer.id);
console.log("Catalog contexts retain independent owners, favorite removal independence and explicit capacity.");
