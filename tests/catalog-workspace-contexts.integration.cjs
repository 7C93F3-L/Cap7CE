const assert = require("node:assert/strict");
const { createCatalogWorkspace, catalogWorkspaceReducer: reduce, maximumCatalogContexts } = require("../src/renderer/catalog-workspace/catalogWorkspaceContexts.ts");
let state = createCatalogWorkspace("All files");
assert.equal(reduce(state, { type: "close", id: state.activeId }), state);
state = reduce(state, { type: "open", scopePath: "Y:\\Fixtures", name: "Fixtures" });
const first = state.contexts[1], firstId = state.activeId;
state = reduce(state, { type: "open", scopePath: "y:/fixtures/", name: "Another alias" });
assert.equal(state.contexts.length, 2);
assert.equal(state.activeId, firstId);
assert.equal(state.contexts[1], first, "Selecting a scope must retain its mounted identity and query owner");
state = reduce(state, { type: "open", scopePath: "Y:\\Fixtures\\Nested", name: "Nested" });
const secondId = state.activeId;
state = reduce(state, { type: "favorite-names", directories: [{ id: "fav", path: "y:\\fixtures\\", name: "Renamed" }] });
assert.equal(state.contexts[1].id, firstId);
assert.equal(state.contexts[1].name, "Renamed");
const renamed = state;
assert.equal(reduce(state, { type: "favorite-names", directories: [] }), renamed,
  "Removing all favorites cannot close, switch or rename open views");
state = reduce(state, { type: "close", id: firstId });
assert.equal(state.activeId, secondId, "Closing an inactive view cannot switch the current view");
state = reduce(state, { type: "close", id: secondId });
assert.equal(state.activeId, "catalog:all");
state = reduce(state, { type: "open", scopePath: "Y:\\Fixtures", name: "Again" });
assert.notEqual(state.activeId, firstId, "Reopening must create a fresh owner after previous query retirement");
const searchOwner = state.contexts.find(context => context.id === state.activeId);
state = reduce(state, { type: "open", kind: "browse", scopePath: "y:/fixtures/", name: "Browser" });
const browserOwner = state.contexts.find(context => context.id === state.activeId);
assert.notEqual(browserOwner.id, searchOwner.id, "Browsing cannot replace the search query owner at the same path");
assert.equal(state.contexts.find(context => context.id === searchOwner.id), searchOwner);
state = reduce(state, { type: "open", kind: "browse", scopePath: "Y:\\Fixtures", name: "Browser again" });
assert.equal(state.activeId, browserOwner.id);
assert.equal(state.contexts.find(context => context.id === browserOwner.id), browserOwner);
state = reduce(state, { type: "open", scopePath: "Y:\\Fixtures", name: "Search again" });
assert.equal(state.activeId, searchOwner.id);
state = reduce(state, { type: "open", kind: "browse", scopePath: null, name: "Skim" });
const browserRoot = state.activeId;
assert.notEqual(browserRoot, "catalog:all");
state = reduce(state, { type: "close", id: browserRoot });
assert.equal(state.contexts.some(context => context.id === browserRoot), false, "Only the search root is pinned");
assert.equal(state.contexts.find(context => context.id === searchOwner.id), searchOwner);
for (let index = state.contexts.length; index < maximumCatalogContexts; index++)
  state = reduce(state, { type: "open", scopePath: `Y:\\Folder${index}`, name: `Folder${index}` });
const full = state;
state = reduce(state, { type: "open", scopePath: "Y:\\Overflow", name: "Overflow" });
assert.equal(state.contexts, full.contexts);
assert.equal(state.activeId, full.activeId);
assert.equal(state.openLimitReached, true, "Capacity cannot silently evict another view");
state = reduce(state, { type: "open", scopePath: null, name: "All files" });
assert.equal(state.activeId, "catalog:all");
assert.equal(state.openLimitReached, false);
const unchanged = state;
assert.equal(reduce(state, { type: "select", id: "unknown" }), unchanged);
assert.equal(reduce(state, { type: "close", id: "unknown" }), unchanged);
assert.equal(reduce(state, { type: "favorite-names", directories: [] }), unchanged);
console.log("Catalog contexts retain independent owners, favorite removal independence and explicit capacity.");
