const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path'), os = require('node:os');
const {app, BrowserWindow, protocol, nativeImage} = require('electron');
const esbuild = require('esbuild');
const temporaryRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'Cap7CE-thumbnail-'));
app.setPath('userData', temporaryRoot + '-profile');
protocol.registerSchemesAsPrivileged([{scheme:'cap7ce', privileges:{standard:true,secure:true,supportFetchAPI:true}}]);
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
let protocolDelay = 0, window;
const fixture = `
import React,{useState,useRef,useEffect} from 'react';
import {createRoot} from 'react-dom/client';
import {useViewportThumbnail} from './src/renderer/computer-search/useViewportThumbnail';
const probe=window.probe={events:[],pictures:[],delay:0};let sequence=0;
window.cap7ce={computerSearch:{acquireThumbnail:async request=>{const id='lease-'+(++sequence);probe.events.push({kind:'acquire',id,...request});await new Promise(r=>setTimeout(r,probe.delay));return id},releaseThumbnail:async request=>{probe.events.push({kind:'release',...request});return true}}};
function Tile({config,scroll}){const thumb=useViewportThumbnail(config.task,config.auth,config.foreground,scroll,config.version);
 useEffect(()=>{if(thumb.image)probe.pictures.push(thumb.image)},[thumb.image]);
 return <span ref={thumb.visualRef} style={{display:'block',width:80,height:80}}>{thumb.image?<canvas data-ready width={thumb.image.width} height={thumb.image.height}/>:<b data-fallback>fallback</b>}</span>}
function App(){const [config,set]=useState({task:'A',auth:'a',foreground:true,version:'one',mounted:true});probe.update=patch=>set(c=>({...c,...patch}));const scroll=useRef(null);
 return <div id="viewport" ref={scroll} style={{height:100,width:100,overflow:'auto'}}>{config.mounted&&<Tile config={config} scroll={scroll}/>}<div style={{height:400}}/></div>}
createRoot(document.getElementById('root')).render(<React.StrictMode><App/></React.StrictMode>);
`;
app.whenReady().then(async () => {
  try {
    const png = nativeImage.createFromBitmap(Buffer.from([0,0,255,255,0,255,0,255]), {width:2,height:1}).toPNG();
    protocol.handle('cap7ce', async () => { await wait(protocolDelay); return new Response(png,{headers:{'content-type':'image/png'}}); });
    const bundle = esbuild.buildSync({stdin:{contents:fixture,resolveDir:path.resolve(__dirname,'..'),loader:'tsx'},bundle:true,platform:'browser',write:false,define:{'process.env.NODE_ENV':'"development"'}}).outputFiles[0].text;
    fs.writeFileSync(path.join(temporaryRoot,'fixture.js'),bundle);
    fs.writeFileSync(path.join(temporaryRoot,'index.html'),'<div id="root"></div><script src="fixture.js"></script>');
    window = new BrowserWindow({show:false,width:300,height:300,webPreferences:{sandbox:true,contextIsolation:true,nodeIntegration:false,backgroundThrottling:false}});
    const run = code => window.webContents.executeJavaScript(code);
    const ready = async code => { for(let n=0;n<100;n++){if(await run(code))return;await wait(20)}throw Error('timeout: '+code); };
    const count = () => run("document.querySelectorAll('[data-ready]').length");
    const acquired = () => run("probe.events.filter(e=>e.kind==='acquire').length");
    await window.loadFile(path.join(temporaryRoot,'index.html'));
    await ready("document.querySelector('[data-ready]')");
    assert.equal(await run('probe.pictures.at(-1).width/probe.pictures.at(-1).height'),2,'decoded thumbnail retains original aspect ratio');
    await run("probe.transitions=[];probe.observer=new MutationObserver(()=>probe.transitions.push(document.querySelectorAll('[data-ready]').length));probe.observer.observe(document.querySelector('#viewport'),{childList:true,subtree:true})");
    await run("probe.update({foreground:false})");await wait(100);
    assert.equal(await count(),1,'blur retains decoded pixels');
    const before = await acquired();
    await run("probe.update({task:'B',auth:'b'})");await wait(100);
    assert.equal(await acquired(),before,'background owner change cannot start work');assert.equal(await count(),1);
    protocolDelay=100;
    await run("probe.update({foreground:true})");await wait(250);
    assert.equal(await count(),1);
    assert.deepEqual(await run('probe.transitions.filter(n=>n===0)'),[],'unchanged handoff never clears presentation');
    await run("probe.update({version:'two'})");await wait(40);
    assert.equal(await count(),0,'source version change drops old pixels immediately');
    assert.equal(await run('probe.pictures[0].width'),0,'replaced pixels are released');
    await ready("document.querySelector('[data-ready]')");
    await run("document.querySelector('#viewport').scrollTop=200");
    await ready("!document.querySelector('[data-ready]')");
    assert.equal(await run('probe.pictures.at(-1).width'),0,'offscreen pixels are released');
    await run("probe.update({foreground:false});document.querySelector('#viewport').scrollTop=0");await wait(100);
    const paused = await acquired();
    await wait(100);assert.equal(await acquired(),paused);
    await run("probe.delay=200;probe.update({foreground:true})");
    await ready(`probe.events.filter(e=>e.kind==='acquire').length>${paused}`);
    const lateId = await run("probe.events.filter(e=>e.kind==='acquire').at(-1).id");
    await run("probe.update({foreground:false})");await wait(300);
    assert.equal(await count(),0);
    assert.equal(await run(`probe.events.filter(e=>e.kind==='release'&&e.leaseId===${JSON.stringify(lateId)}).length`),1,'late lease is released once');
    protocolDelay=200;
    await run("probe.delay=0;probe.update({foreground:true,version:'three'})");await wait(50);
    await run("probe.update({foreground:false})");await wait(300);
    assert.equal(await count(),0,'late decode cannot install background pixels');
    protocolDelay=0;
    await run("probe.update({foreground:true})");await ready("document.querySelector('[data-ready]')");
    await run("probe.update({mounted:false})");await wait(100);
    assert.equal(await run('probe.pictures.at(-1).width'),0,'unmount releases retained pixels');
    console.log('Thumbnail pixels preserve aspect and survive blur/owner handoff; source changes, viewport exit, late acquisition/decode and unmount release ownership.');
    window.destroy();
    if(path.dirname(temporaryRoot)!==path.resolve(os.tmpdir()))throw Error('unexpected test cleanup root');
    fs.rmSync(temporaryRoot,{recursive:true,force:true});app.exit(0);
  } catch(error){console.error(error);window?.destroy();app.exit(1)}
});
